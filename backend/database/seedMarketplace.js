async function seedMarketplace() {
  console.log('🌱 [Seeder] Starting SHOPERA Marketplace Database Seeding...');
  const pool = await db.connect();

  try {
    // 1. Seed Categories
    console.log(`📦 Seeding ${categories.length} marketplace categories...`);
    for (const c of categories) {
      await pool.query(
        `INSERT INTO categories (id, name, slug, description, image_url, is_active)
         VALUES (?, ?, ?, ?, ?, ?)
         ON DUPLICATE KEY UPDATE name=VALUES(name), slug=VALUES(slug), description=VALUES(description), image_url=VALUES(image_url), is_active=VALUES(is_active)`,
        [c.id, c.name, c.slug, c.description, c.image_url, c.is_active]
      );
    }
    console.log('✅ Categories seeded successfully.');

    // 2. Seed Coupons
    console.log(`🎟️ Seeding ${coupons.length} promotional coupons...`);
    for (const cp of coupons) {
      await pool.query(
        `INSERT INTO coupons (code, description, discount_type, discount_value, min_order_amount, max_discount_amount, is_active)
         VALUES (?, ?, ?, ?, ?, ?, ?)
         ON DUPLICATE KEY UPDATE description=VALUES(description), discount_type=VALUES(discount_type), discount_value=VALUES(discount_value), min_order_amount=VALUES(min_order_amount), max_discount_amount=VALUES(max_discount_amount), is_active=VALUES(is_active)`,
        [cp.code, cp.description, cp.discount_type, cp.discount_value, cp.min_order_amount, cp.max_discount_amount, cp.is_active]
      );
    }
    console.log('✅ Coupons seeded successfully.');

    // 3. Seed Products
    console.log(`🛍️ Seeding ${products.length} distinct marketplace products (10-12 per category)...`);
    for (const p of products) {
      await pool.query(
        `INSERT INTO products (
          id, category_id, brand, title, slug, sku, price, discount_price, stock_quantity,
          short_description, description, image_url, additional_images, specifications, variants,
          is_featured, is_active, rating, num_reviews
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON DUPLICATE KEY UPDATE
          category_id=VALUES(category_id),
          brand=VALUES(brand),
          title=VALUES(title),
          slug=VALUES(slug),
          price=VALUES(price),
          discount_price=VALUES(discount_price),
          stock_quantity=VALUES(stock_quantity),
          short_description=VALUES(short_description),
          description=VALUES(description),
          image_url=VALUES(image_url),
          additional_images=VALUES(additional_images),
          specifications=VALUES(specifications),
          variants=VALUES(variants),
          is_featured=VALUES(is_featured),
          is_active=VALUES(is_active),
          rating=VALUES(rating),
          num_reviews=VALUES(num_reviews)`,
        [
          p.id, p.category_id, p.brand, p.title, p.slug, p.sku, p.price, p.discount_price,
          p.stock_quantity, p.short_description, p.description, p.image_url,
          p.additional_images, p.specifications, p.variants, p.is_featured, p.is_active,
          p.rating, p.num_reviews
        ]
      );
    }
    console.log('✅ Products seeded successfully.');

    // 4. Verify counts
    const [catCount] = await pool.query('SELECT count(*) as count FROM categories');
    const [prodCount] = await pool.query('SELECT count(*) as count FROM products');
    const [couponCount] = await pool.query('SELECT count(*) as count FROM coupons');

    console.log(`\n🎉 SEEDING COMPLETE:`);
    console.log(`- Categories in DB: ${catCount[0].count}`);
    console.log(`- Products in DB:   ${prodCount[0].count}`);
    console.log(`- Coupons in DB:    ${couponCount[0].count}`);

  } catch (err) {
    console.error('❌ Error seeding marketplace:', err);
    throw err;
  }
}

if (require.main === module) {
  seedMarketplace().then(() => process.exit(0)).catch(err => {
    console.error(err);
    process.exit(1);
  });
}

module.exports = seedMarketplace;
